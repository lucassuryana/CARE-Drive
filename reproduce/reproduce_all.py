"""
Reproduce every reported CARE-Drive result from the archived data -- no API
calls, no GPU.

    python -m reproduce.reproduce_all            # descriptive checks (~20 s)
    python -m reproduce.reproduce_all --stats    # + Tables 6-8 (~2 min)

Writes to reproduce/output/:
    verification.csv / verification.md   check-by-check comparison with the paper
    *.csv                                 the recomputed tables themselves
    stage2_analysis_output/               (--stats) CSVs of the Stage 2 analysis
"""

import argparse
import sys
from pathlib import Path

from . import results as r
from .verify import all_checks

OUT = Path(__file__).resolve().parent / "output"


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--stats", action="store_true",
                    help="also rerun the Stage 2 regression/bootstrap analysis (Tables 6-8)")
    args = ap.parse_args(argv)
    OUT.mkdir(exist_ok=True)

    t4, t5 = r.stage1_record()
    tables = {
        "table4_stage1_record": t4,
        "table5_stage1_record": t5,
        "fig5_stage2_cells_ToT": r.stage2_cells("ToT"),
        "fig5_stage2_cells_CoT": r.stage2_cells("CoT"),
        "table9_gpt": r.ablation_table("gpt"),
        "table9_qwen": r.ablation_table("qwen"),
        "fig6b_conditionE_gpt": r.ablation_E_breakdown("gpt"),
        "ablation_workbook_conditionE_unused": r.ablation_file_condition_E(),
        "tableA12_gpt": r.speed_offset_table("gpt"),
        "tableA12_gpt_directional_agreement": r.speed_offset_directional_agreement("gpt"),
        "tableA12_qwen_exploratory": r.speed_offset_table("qwen"),
    }
    for name, df in tables.items():
        df.to_csv(OUT / f"{name}.csv", index=False)

    checks = all_checks(OUT / "stage2_analysis_output" if args.stats else None)
    checks.to_csv(OUT / "verification.csv", index=False)

    lines = ["# Verification against the manuscript", "",
             "Generated by `python -m reproduce.reproduce_all"
             + (" --stats" if args.stats else "") + "`.", "",
             "| status | check | manuscript | expected | observed |",
             "|---|---|---|---|---|"]
    for c in checks.itertuples():
        lines.append(f"| {c.status} | {c.id} | {c.ref} | {c.expected} | {c.observed} |")
    (OUT / "verification.md").write_text("\n".join(lines) + "\n")

    summary = checks.status.value_counts()
    print(summary.to_string())
    for c in checks[checks.status == "MISMATCH"].itertuples():
        print(f"MISMATCH  {c.id}: expected {c.expected}, observed {c.observed}")
    print(f"\nWritten to {OUT}/")
    return 0


if __name__ == "__main__":
    sys.exit(main())
